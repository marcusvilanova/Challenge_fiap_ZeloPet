-- Zelo — schema inicial (Sprint 4). SQL portável: H2 (demo) e Oracle 12c+ (IDENTITY / CLOB / TIMESTAMP).

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(160) NOT NULL,
    display_name  VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_role CHECK (role IN ('TUTOR', 'CLINICA'))
);

CREATE TABLE pet (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT       NOT NULL,
    name         VARCHAR(80)  NOT NULL,
    species      VARCHAR(10)  NOT NULL,
    breed        VARCHAR(80),
    female       BOOLEAN      NOT NULL,
    birth_date   DATE,
    weight_kg    NUMERIC(6, 2),
    history_tags VARCHAR(400),
    created_at   TIMESTAMP    NOT NULL,
    CONSTRAINT fk_pet_owner FOREIGN KEY (owner_id) REFERENCES app_user (id),
    CONSTRAINT ck_pet_species CHECK (species IN ('DOG', 'CAT'))
);
CREATE INDEX ix_pet_owner ON pet (owner_id);

CREATE TABLE care_item (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id    BIGINT       NOT NULL,
    type      VARCHAR(20)  NOT NULL,
    name      VARCHAR(120) NOT NULL,
    last_done DATE,
    next_due  DATE         NOT NULL,
    CONSTRAINT fk_care_item_pet FOREIGN KEY (pet_id) REFERENCES pet (id)
);
CREATE INDEX ix_care_item_pet ON care_item (pet_id);

CREATE TABLE chat_session (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id     BIGINT    NOT NULL,
    user_id    BIGINT    NOT NULL,
    state_json CLOB      NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_chat_session_pet FOREIGN KEY (pet_id) REFERENCES pet (id),
    CONSTRAINT fk_chat_session_user FOREIGN KEY (user_id) REFERENCES app_user (id)
);
CREATE INDEX ix_chat_session_pet ON chat_session (pet_id);

CREATE TABLE chat_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT      NOT NULL,
    role       VARCHAR(10) NOT NULL,
    content    CLOB        NOT NULL,
    meta_json  CLOB,
    created_at TIMESTAMP   NOT NULL,
    CONSTRAINT fk_chat_message_session FOREIGN KEY (session_id) REFERENCES chat_session (id),
    CONSTRAINT ck_chat_message_role CHECK (role IN ('USER', 'BOT'))
);
CREATE INDEX ix_chat_message_session ON chat_message (session_id);

CREATE TABLE triage (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id                BIGINT       NOT NULL,
    session_id            BIGINT,
    source                VARCHAR(20)  NOT NULL,
    input_text            CLOB         NOT NULL,
    result_json           CLOB         NOT NULL,
    priority              VARCHAR(12)  NOT NULL,
    next_action           VARCHAR(40)  NOT NULL,
    confidence            NUMERIC(4, 2) NOT NULL,
    model_version         VARCHAR(60)  NOT NULL,
    human_review_required BOOLEAN      NOT NULL,
    shared_with_clinic    BOOLEAN      NOT NULL,
    created_at            TIMESTAMP    NOT NULL,
    CONSTRAINT fk_triage_pet FOREIGN KEY (pet_id) REFERENCES pet (id),
    CONSTRAINT fk_triage_session FOREIGN KEY (session_id) REFERENCES chat_session (id),
    CONSTRAINT ck_triage_priority CHECK (priority IN ('baixa', 'media', 'alta', 'emergencia'))
);
CREATE INDEX ix_triage_pet ON triage (pet_id);
CREATE INDEX ix_triage_shared ON triage (shared_with_clinic, created_at);

CREATE TABLE timeline_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id       BIGINT       NOT NULL,
    type         VARCHAR(30)  NOT NULL,
    title        VARCHAR(160) NOT NULL,
    summary      VARCHAR(500),
    source       VARCHAR(30)  NOT NULL,
    ref_id       BIGINT,
    payload_json CLOB,
    occurred_at  TIMESTAMP    NOT NULL,
    CONSTRAINT fk_timeline_pet FOREIGN KEY (pet_id) REFERENCES pet (id)
);
CREATE INDEX ix_timeline_pet ON timeline_event (pet_id, occurred_at);

CREATE TABLE consent (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id     BIGINT       NOT NULL,
    granted_by BIGINT       NOT NULL,
    scope      VARCHAR(60)  NOT NULL,
    version    VARCHAR(20)  NOT NULL,
    recipient  VARCHAR(80)  NOT NULL,
    granted_at TIMESTAMP    NOT NULL,
    revoked_at TIMESTAMP,
    CONSTRAINT fk_consent_pet FOREIGN KEY (pet_id) REFERENCES pet (id),
    CONSTRAINT fk_consent_user FOREIGN KEY (granted_by) REFERENCES app_user (id)
);
CREATE INDEX ix_consent_pet ON consent (pet_id);

CREATE TABLE clinic_review (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    triage_id      BIGINT       NOT NULL,
    reviewer_id    BIGINT       NOT NULL,
    decision       VARCHAR(20)  NOT NULL,
    final_priority VARCHAR(12)  NOT NULL,
    note           VARCHAR(1000),
    created_at     TIMESTAMP    NOT NULL,
    CONSTRAINT fk_review_triage FOREIGN KEY (triage_id) REFERENCES triage (id),
    CONSTRAINT fk_review_user FOREIGN KEY (reviewer_id) REFERENCES app_user (id),
    CONSTRAINT ck_review_decision CHECK (decision IN ('CONFIRMADA', 'AJUSTADA'))
);
CREATE INDEX ix_review_triage ON clinic_review (triage_id);

CREATE TABLE image_analysis (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id      BIGINT      NOT NULL,
    sha256      VARCHAR(64) NOT NULL,
    result_json CLOB        NOT NULL,
    created_at  TIMESTAMP   NOT NULL,
    CONSTRAINT fk_image_pet FOREIGN KEY (pet_id) REFERENCES pet (id)
);
CREATE INDEX ix_image_pet ON image_analysis (pet_id);
